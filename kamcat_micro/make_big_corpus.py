def fill_template(template):
    """Заполняет ВСЕ плейсхолдеры {...} в шаблоне."""
    result = template
    for _ in range(100):
        match = re.search(r"\{([^}]+)\}", result)
        if not match:
            break
        key = match.group(1)
        replacement = random.choice(TOPICS[key]) if key in TOPICS else "?"
        result = result.replace(match.group(0), replacement, 1)
    return result


def make_big_corpus(output_path="data/corpus.txt", target_size_mb=2.5):
    Path(output_path).parent.mkdir(exist_ok=True)
    target_bytes = int(target_size_mb * 1024 * 1024)
    lines = []
    current_bytes = 0

    print(f"Генерируем корпус до {target_size_mb} МБ...")

    while current_bytes < target_bytes:
        template = random.choice(TEMPLATES)
        line = fill_template(template)
        lines.append(line)
        current_bytes += len(line.encode("utf-8")) + 1

        if len(lines) % 10000 == 0:
            print(f"  {len(lines):,} строк, {current_bytes / 1024 / 1024:.2f} МБ")

    random.shuffle(lines)

    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    size_mb = Path(output_path).stat().st_size / 1024 / 1024
    print(f"\n✅ Корпус создан: {output_path}")
    print(f"   Размер: {size_mb:.2f} МБ")
    print(f"   Строк: {len(lines):,}")

    # Проверка
    with open(output_path, encoding="utf-8") as f:
        content = f.read()
    leftover = re.findall(r"\{[^}]+\}", content)
    if leftover:
        print(f"   ⚠️ Осталось {len(leftover)} плейсхолдеров: {list(set(leftover))[:5]}")
    else:
        print(f"   ✅ Все плейсхолдеры заполнены!")


