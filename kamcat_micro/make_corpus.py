def make_corpus(output_path="data/corpus.txt", target_size_kb=200):
    """Генерирует корпус из шаблонов"""
    Path(output_path).parent.mkdir(exist_ok=True)

    lines = []
    target_size = target_size_kb * 1024
    current_size = 0

    while current_size < target_size:
        # Случайная фраза
        line = random.choice(TEMPLATES)
        lines.append(line)
        current_size += len(line.encode("utf-8"))

        # Иногда добавляем пустую строку (разделитель)
        if random.random() < 0.1:
            lines.append("")
            current_size += 1

    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    size_kb = Path(output_path).stat().st_size / 1024
    print(f"✅ Корпус создан: {output_path}")
    print(f"   Размер: {size_kb:.1f} КБ")
    print(f"   Строк: {len(lines)}")

if __name__ == "__main__":
    make_corpus()